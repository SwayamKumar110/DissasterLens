import os
import datetime
from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware
from fastapi.staticfiles import StaticFiles

from app.routes import analysis, dashboard, research, examples

app = FastAPI(
    title="DisasterLens AI - Multimodal Disaster Prediction API",
    description="Backend API for Explainable Foundation Model for Multimodal Disaster Prediction research project",
    version="1.0.0"
)

# Enable CORS for React frontend
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

# Serve static sample images
static_dir = os.path.join(os.path.dirname(__file__), "..", "static")
if not os.path.exists(static_dir):
    os.makedirs(static_dir, exist_ok=True)
app.mount("/static", StaticFiles(directory=static_dir), name="static")

# Include API Routers
app.include_router(analysis.router)
app.include_router(dashboard.router)
app.include_router(research.router)
app.include_router(examples.router)

@app.get("/api/health")
async def health_check():
    return {
        "status": "healthy",
        "service": "DisasterLens AI",
        "timestamp": datetime.datetime.now().isoformat(),
        "mode": "Demonstration Mode (Academic Presentation)",
        "disclaimer": "Demonstration prediction — not generated by a trained research model."
    }

@app.get("/")
async def root():
    return {
        "message": "Welcome to DisasterLens AI API",
        "documentation": "/docs",
        "health": "/api/health"
    }

if __name__ == "__main__":
    import uvicorn
    uvicorn.run("app.main:app", host="0.0.0.0", port=8000, reload=True)

