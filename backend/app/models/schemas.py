from typing import List, Dict, Optional, Any
from pydantic import BaseModel, Field

class ClassificationResult(BaseModel):
    task: str
    predicted_class: str
    confidence: float
    all_probabilities: Dict[str, float]
    explanation: str
    status_type: str = "info"  # "danger", "warning", "success", "info"

class FeatureImportance(BaseModel):
    feature: str
    score: float
    impact: str  # "positive", "negative"
    modality: str  # "text", "visual"

class TextTokenExplanation(BaseModel):
    text: str
    weight: float
    importance_level: str  # "high", "medium", "neutral", "low"

class TextExplanation(BaseModel):
    tokens: List[TextTokenExplanation]
    top_features: List[FeatureImportance]
    summary: str

class VisualRegion(BaseModel):
    id: str
    name: str
    importance: str  # "High", "Medium", "Low"
    weight: float
    box: List[float]  # [ymin, xmin, ymax, xmax] percentages 0-100
    description: str

class VisualExplanation(BaseModel):
    regions: List[VisualRegion]
    summary: str
    heatmap_colors: Dict[str, str]

class MultimodalFusionDetails(BaseModel):
    visual_feature_dim: int = 2048
    textual_feature_dim: int = 768
    fused_dim: int = 512
    visual_weight: float = 0.48
    textual_weight: float = 0.52
    fusion_method: str = "Concatenation + Gated Cross-Attention Linear Projection"
    stage_breakdown: List[Dict[str, str]]

class AnalysisResponse(BaseModel):
    analysis_id: str
    timestamp: str
    is_demo_mode: bool = True
    disclaimer: str = "Demonstration prediction — not generated by a trained research model."
    image_info: Dict[str, Any]
    text_info: Dict[str, Any]
    classifications: Dict[str, ClassificationResult]
    text_explanation: TextExplanation
    visual_explanation: VisualExplanation
    fusion_details: MultimodalFusionDetails

class KPIData(BaseModel):
    total_analyses: int
    high_urgency_cases: int
    damage_detected: int
    relief_required: int

class RecentAnalysis(BaseModel):
    case_id: str
    disaster_type: str
    urgency: str
    damage_level: str
    relief_required: str
    analysis_date: str

class CategoryDistribution(BaseModel):
    name: str
    value: int
    color: str

class ActivityDataPoint(BaseModel):
    time: str
    analyses: int
    high_urgency: int

class DashboardData(BaseModel):
    kpis: KPIData
    recent_analyses: List[RecentAnalysis]
    distribution: List[CategoryDistribution]
    activity_timeline: List[ActivityDataPoint]

class AccuracyItem(BaseModel):
    task: str
    baseline_accuracy: float
    proposed_accuracy: float

class F1Item(BaseModel):
    task: str
    baseline_macro_f1: float
    baseline_micro_f1: float
    proposed_macro_f1: float
    proposed_micro_f1: float

class EfficiencyItem(BaseModel):
    model: str
    parameters: str
    flops: str
    latency: str
    throughput: str

class ResearchInsights(BaseModel):
    accuracy_comparison: List[AccuracyItem]
    f1_comparison: List[F1Item]
    computational_efficiency: List[EfficiencyItem]
    key_findings: List[str]
    academic_disclaimer: str

class ExampleCase(BaseModel):
    id: str
    title: str
    category: str
    image_filename: str
    image_url: str
    text_report: str
    expected_outputs: Dict[str, str]

